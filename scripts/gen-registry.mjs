// Lists every feature group's tools and extensions in
// src/features/registry.generated.ts: groups are folders with an index.ts that
// exports `tools`, and may also export `extensions` (src/core/extensions.ts).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// Another folder only for the script's own test.
const dir = process.env.LOOKER_STUDIO_MCP_FEATURES ?? join(root, 'src/features');
const groups = readdirSync(dir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(dir, d.name, 'index.ts')))
  .map((d) => d.name)
  .sort();
const exportsExtensions = (g) =>
  /export\s+(?:const|let|var)\s+extensions\b|export\s*\{[^}]*\bextensions\b[^}]*\}/.test(readFileSync(join(dir, g, 'index.ts'), 'utf8'));
const withExt = groups.filter(exportsExtensions);
// Group names can be reserved words (static): prefix them.
const ident = (g) => `${g.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())}Group`;
const body = [
  '// Generated by scripts/gen-registry.mjs from src/features/*/index.ts. Do not edit.',
  "import type { FeatureExtensions } from '../core/extensions.js';",
  "import type { Tool } from '../core/tool.js';",
  ...groups.map(
    (g) => `import { tools as ${ident(g)}${withExt.includes(g) ? `, extensions as ${ident(g)}Ext` : ''} } from './${g}/index.js';`,
  ),
  '',
  `export const FEATURE_TOOLS: Tool[] = [${groups.map((g) => `...${ident(g)}`).join(', ')}];`,
  '',
  `export const FEATURE_EXTENSIONS: Array<{ group: string; extensions: FeatureExtensions }> = [${withExt
    .map((g) => `{ group: '${g}', extensions: ${ident(g)}Ext }`)
    .join(', ')}];`,
  '',
].join('\n');
const out = join(dir, 'registry.generated.ts');
if (!existsSync(out) || readFileSync(out, 'utf8') !== body) writeFileSync(out, body);
console.log(
  `registry: ${groups.length} feature groups${groups.length ? ` (${groups.join(', ')})` : ''}, ${withExt.length} with extensions`,
);
